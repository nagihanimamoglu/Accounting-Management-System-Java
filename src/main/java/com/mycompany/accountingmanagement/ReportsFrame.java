    private void ExportButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ExportButtonActionPerformed
        // TODO add your handling code here:
        try{                     
            FileWriter writer = new FileWriter("AllFinancialReport_" + "_" + LocalDate.now() + ".txt");
            writer.write("Financial Reports (" + LocalDate.now() + ")\n\n");
            
            for(int i = 0; i < Table.getRowCount(); i++){
                String username = Table.getValueAt(i, 1).toString();
                String income = Table.getValueAt(i, 2).toString();
                String expense = Table.getValueAt(i, 3).toString();
                String balance = Table.getValueAt(i, 4).toString();
                
                writer.write(username + "\n");
                writer.write("Income: " + income + "TL\n");
                writer.write("Expense: " + expense + "TL\n");
                writer.write("Balance: " + balance + "TL\n");     
            }
            writer.close();
            JOptionPane.showMessageDialog(null, "Reports exported successfully!");
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_ExportButtonActionPerformed

