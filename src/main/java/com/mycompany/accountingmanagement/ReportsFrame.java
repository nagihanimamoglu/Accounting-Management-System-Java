    public void loadReports(){
        DefaultTableModel model = new DefaultTableModel(new String[]{
            "Id","Name Surname","Total Income","Total Expense","Net Balance"},0);
        Table.setModel(model);
        
        String usersQuery = "SELECT id, name_surname FROM users";
        String incomeQuery = "SELECT SUM(amount) FROM transactions WHERE user_id = ? AND type = ?";
        String expenseQuery = "SELECT SUM(amount) FROM transactions WHERE user_id = ? AND type = ?";
        
        try(
               Connection connection = DriverManager.getConnection(connectionString);
               PreparedStatement stUsers = connection.prepareStatement(usersQuery);
                PreparedStatement stIncome = connection.prepareStatement(incomeQuery);
                PreparedStatement stExpense = connection.prepareStatement(expenseQuery);
                ResultSet rsUsers = stUsers.executeQuery()
                ){
            while(rsUsers.next()){
                int id = rsUsers.getInt("id");
                String nameSurname = rsUsers.getString("name_surname");
                
                stIncome.setInt(1, id);
                stIncome.setString(2, "income");
                
                stExpense.setInt(1, id);
                stExpense.setString(2, "expense");
                
                ResultSet rsIncome = stIncome.executeQuery();
                ResultSet rsExpense = stExpense.executeQuery();
                
                float income = 0, expense = 0;
                if(rsIncome.next()){
                    income = rsIncome.getFloat(1);
                }
                if(rsExpense.next()){
                    expense = rsExpense.getFloat(1);
                }
                float balance = income - expense;
                
                model.addRow(new Object[]{id,nameSurname,income,expense,balance});
            }
        } catch(SQLException e){
            JOptionPane.showMessageDialog(null,"Database error: " + e.getMessage());
        }   
    }

