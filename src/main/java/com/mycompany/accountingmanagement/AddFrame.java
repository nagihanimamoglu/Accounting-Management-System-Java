    private void SaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveButtonActionPerformed
        // TODO add your handling code here:
        if (Amount.getValue() == null || TypeBox.getSelectedItem() == null || CurrencyBox.getSelectedItem() == null || List.getSelectedValue() == null) {
            Label6.setVisible(true);
            return;
        }

        String type = TypeBox.getSelectedItem().toString();
        String category = List.getSelectedValue();
        float amount = Float.parseFloat(Amount.getValue().toString());
        String description = TextArea.getText();
        String currency = CurrencyBox.getSelectedItem().toString();
        int user_id = this.user_id;
        String username_surname = this.username_surname;
        
        if(amount <= 0){
            JOptionPane.showMessageDialog(null,"Amount must be positive!");
            return;
        }

        if (UserTransactions.addTransaction(type, category, amount, description, user_id, username_surname, currency)) {
            JOptionPane.showMessageDialog(null, "Transaction added successfully!");
            TypeBox.setSelectedIndex(0);
            List.setSelectedIndex(0);
            Amount.setValue(0);
            TextArea.setText("");
            CurrencyBox.setSelectedIndex(0);
            Label6.setVisible(false);
        } else {
            JOptionPane.showMessageDialog(null, "Transaction is failed!");
        }
    }//GEN-LAST:event_SaveButtonActionPerformed

