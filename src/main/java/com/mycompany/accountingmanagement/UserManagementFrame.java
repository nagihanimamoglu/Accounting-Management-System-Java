    public void updateTable() {
        DefaultTableModel model1 = new DefaultTableModel(new String[]{
            "id", "name_surname","email","password","gender","role"},0);
        
        DefaultTableModel model2 = new DefaultTableModel(new String[]{
            "id", "name_surname","email","password","gender","role"},0);
        
        UsersTable.setModel(model1);
        UsersTable2.setModel(model2);

        String query = "SELECT * FROM users";
        try (
                Connection connection = DriverManager.getConnection(connectionString);
                PreparedStatement statement = connection.prepareStatement(query);
                ResultSet rs = statement.executeQuery();) {
            while (rs != null && rs.next()) {
               Object[] rowData = new Object[]{
                    rs.getInt("id"),
                    rs.getString("name_surname"),
                    rs.getString("email"),
                    rs.getString("password"),
                    rs.getString("gender"),
                    rs.getString("role")
                };
               model1.addRow(rowData);
               model2.addRow(rowData);
            }
        } catch (SQLException ex) {
            System.out.println("Updating Error: " + ex.getMessage());
        }
    }

