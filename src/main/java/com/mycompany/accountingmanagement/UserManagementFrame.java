    private void SignupButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SignupButtonActionPerformed
        // TODO add your handling code here:

        String fullname = NameField.getText();
        String email = EmailField.getText();
        String pass = new String(PasswordField.getPassword());
        String pass2 = new String(PasswordField2.getPassword());

        if (fullname.isEmpty() || email.isEmpty() || pass.isEmpty() || pass2.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in the blanks!");
            Label7.setVisible(true);
            return;
        }

        String regexname = "^[a-zA-ZçğıöşüÇĞİÖŞÜ]{2,} [a-zA-ZçğıöşüÇĞİÖŞÜ]{2,}$";
        String regexemail = "^[A-Za-z\\d@$!%*?&.-_+]+@manage\\.com$";
        String regexpass = "^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d)(?=.*[@$!%*?&])[A-Za-z\\d@$!%*?&]{8,}$";

        if (!Pattern.matches(regexname, fullname)) {
            JOptionPane.showMessageDialog(null, "Invalid name!");
            return;
        }

        if (!Pattern.matches(regexemail, email)) {
            JOptionPane.showMessageDialog(null, "Please enter emai adress(username) in company format! It must contain at least one uppercase and lowercase letter, special character and number and extension 'manage.com'!");
            return;
        }

        if (!Pattern.matches(regexpass, pass)) {
            JOptionPane.showMessageDialog(null, "Invalid password! Password must be at least 8 characters, contain uppercase and lowercase letters, special characters and numbers!");
            return;
        }

        if (!pass.equals(pass2)) {
            JOptionPane.showMessageDialog(null, "Passwords do not match!");
            return;
        }

        String gender = FemaleButton.isSelected() ? "Female" : "Male";
        if (!FemaleButton.isSelected() && !MaleButton.isSelected()) {
            JOptionPane.showMessageDialog(null, "Please select an option!");
            Label7.setVisible(true);
            return;
        }

        String role = RoleBox.getSelectedItem().toString();
        if (RoleBox.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(null, "Please select a role!");
            Label7.setVisible(true);
            return;
        }

        AdminTransactions.addUser(fullname, email, pass, gender, role);
    }//GEN-LAST:event_SignupButtonActionPerformed

