    private void UpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = UsersTable2.getSelectedRow();

        if (selectedRow != -1) {
            int id = (int) UsersTable2.getValueAt(selectedRow, 0);

            String name = fullnameField.getText();
            String email = emailField.getText();
            String password = passField.getText();
            String gender = genderField.getText();
            String role = roleField.getText();

            boolean result = AdminTransactions.updateUser(id, name, email, password, gender, role);

            if (result) {
                JOptionPane.showMessageDialog(null, "User updated successfully! ");
                updateTable();
            } else {
                JOptionPane.showMessageDialog(null, "User could not be updated!");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Please select a row!");
        }
    }//GEN-LAST:event_UpdateButtonActionPerformed

